def get_procurement_policy(
    region_code: str = "GLOBAL_DEFAULT",
    produce_type: Optional[str] = None,
) -> ProcurementConstraints:
    """Retrieve active procurement policy with hierarchical fallback:
    
    1. Specific {region_code}:{produce_type}
    2. Specific {region_code}
    3. GLOBAL_DEFAULT fallback
    """
    if produce_type:
        key_commodity = f"{region_code}:{produce_type.strip().lower()}"
        if key_commodity in _PROCUREMENT_POLICIES:
            return _PROCUREMENT_POLICIES[key_commodity]

    if region_code in _PROCUREMENT_POLICIES:
        return _PROCUREMENT_POLICIES[region_code]

    return _PROCUREMENT_POLICIES["GLOBAL_DEFAULT"]


def register_procurement_policy(policy: ProcurementConstraints) -> None:
    """Register or override a procurement policy dynamically (for test/admin configuration)."""
    if policy.produce_type:
        key = f"{policy.region_code}:{policy.produce_type.strip().lower()}"
    else:
        key = policy.region_code
    _PROCUREMENT_POLICIES[key] = policy
